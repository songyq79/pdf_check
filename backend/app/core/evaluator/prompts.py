"""
论文评价系统 - 提示词模板 v2

改进要点（v2）：
1. 追问式提示词：要求 AI 引用原文具体内容举证，禁止泛泛而谈
2. 各维度按需取内容：不同维度只看最相关的部分，提升评价针对性
3. 明确禁止套话：在提示词里显式列出不允许出现的模板化表述
4. 提供章节结构：让 AI 先理解论文骨架再评价
"""

# ─────────────────────────────────────────────────────────────
# 学术规范性：大纲 + 摘要 + 结论 + 参考文献
# ─────────────────────────────────────────────────────────────
PROMPT_ACADEMIC_STANDARD = """你是一位严格的学术论文评审专家。请对以下论文进行学术规范性评价。

【论文标题】
{title}

【论文章节大纲】
{outline}

【摘要】
{abstract}

【结论部分】
{conclusion}

【参考文献（前20条）】
{references}

---
请按以下要求进行评价，务必做到：
① 每条优点和问题都必须引用论文中的具体内容作为依据（如具体章节、具体表述），不允许写"结构完整"、"格式规范"等空洞套话
② weaknesses 必须指出具体位置的具体问题，例如"第X章缺少XX"、"参考文献第X条格式有误"
③ suggestions 必须是可操作的具体建议，而不是"建议加强"、"注意规范"等无意义表述

评价角度：
1. 论文结构完整性：对照学术论文标准结构（摘要→引言→文献综述→研究方法→结果分析→结论→参考文献），逐项检查哪些部分存在或缺失
2. 学术用语规范性：从摘要和结论中找出是否有口语化、模糊化的表述，具体指出
3. 参考文献格式：检查参考文献是否符合 GB/T 7714 规范，指出具体格式错误

请按以下 JSON 格式输出，不要输出任何其他文字：
{{
  "score": 85,
  "strengths": ["基于原文具体内容的优点1", "基于原文具体内容的优点2"],
  "weaknesses": ["具体位置+具体问题1", "具体位置+具体问题2"],
  "suggestions": ["可操作的具体建议1", "可操作的具体建议2"]
}}"""


# ─────────────────────────────────────────────────────────────
# 逻辑与创新性：大纲 + 各章摘要 + 结论
# ─────────────────────────────────────────────────────────────
PROMPT_LOGIC_INNOVATION = """你是一位资深学术评审专家。请对以下论文的逻辑性和研究价值进行评价。

【论文标题】
{title}

【论文章节大纲】
{outline}

【各章节内容摘要】
{chapter_summaries}

【结论部分】
{conclusion}

---
请按以下要求进行评价，务必做到：
① 结合章节大纲和各章内容，评判"研究问题→研究方法→分析过程→结论"这条逻辑链是否完整自洽
② 找出逻辑断裂点：哪个环节论证不充分、跳跃、或与其他章节矛盾，请具体说明
③ 评价研究价值时，要结合论文的具体研究对象，而非泛泛说"有一定研究意义"
④ 禁止出现"研究具有一定创新性"、"具有理论与实践意义"等套话

评价角度：
1. 逻辑链完整性：从大纲结构判断各章之间的递进关系是否合理，找出脱节之处
2. 论证充分性：核心论点是否有足够的数据、案例或文献支撑，还是仅靠描述性陈述
3. 研究价值：结合具体研究对象，指出这项研究解决了什么实际问题或填补了什么空白

请按以下 JSON 格式输出，不要输出任何其他文字：
{{
  "score": 80,
  "strengths": ["结合具体章节内容的优点1", "结合具体章节内容的优点2"],
  "weaknesses": ["具体章节+具体逻辑问题1", "具体章节+具体逻辑问题2"],
  "suggestions": ["针对具体逻辑断裂的修改建议1", "针对具体逻辑断裂的修改建议2"]
}}"""


# ─────────────────────────────────────────────────────────────
# 语言质量：从不同章节抽取的文本样本
# ─────────────────────────────────────────────────────────────
PROMPT_LANGUAGE_QUALITY = """你是一位资深学术编辑。请对以下论文的语言质量进行评价。

【论文标题】
{title}

【正文样本（从不同章节抽取）】
{language_sample}

---
请按以下要求进行评价，务必做到：
① 从提供的文本样本中找出具体的语言问题句子，直接引用原文问题句，然后指出问题所在
② 评价语言优点时，同样要引用具体表述作为例证
③ 改进建议要给出"原句→修改后"的具体示例，而不是"建议语言更精炼"这类废话
④ 禁止出现"语言流畅"、"表达清晰"、"文字精炼"等不加分析的空洞评价

评价角度：
1. 术语准确性：专业术语使用是否准确，有无概念混用或错误
2. 句子表达：是否存在歧义句、成分残缺、逻辑不通的句子，直接引用原文中的问题句
3. 冗余表达：找出重复啰嗦、可以精简的表达，给出精简示例

请按以下 JSON 格式输出，不要输出任何其他文字：
{{
  "score": 88,
  "strengths": ["引用原文具体表述的优点1", "引用原文具体表述的优点2"],
  "weaknesses": ["原文问题句+问题说明1", "原文问题句+问题说明2"],
  "suggestions": ["原句→改后示例1", "原句→改后示例2"]
}}"""


# ─────────────────────────────────────────────────────────────
