PROMPT_CITATION_STANDARD = """你是一位熟悉 GB/T 7714 标准的学术规范专家。请对以下论文的文献引用规范性进行评价。

【论文标题】
{title}

【参考文献列表】
{references}

【正文引用标注抽样（含上下文）】
{citation_samples}

---
请按以下要求进行评价，务必做到：
① 逐条检查参考文献格式，指出具体哪几条存在什么格式问题（如作者格式、年份位置、期刊名、页码格式等）
② 从引用标注抽样中，判断正文引用是否与参考文献列表对应，有无引而不列或列而不引的情况
③ 评价文献质量时，分析文献的时效性（近5年文献占比）和权威性
④ 禁止出现"参考文献较为丰富"、"引用较为规范"等模糊评价

评价角度：
1. 格式规范性：对照 GB/T 7714，找出具体格式错误，指出是第几条、什么问题
2. 文献质量：分析文献是否覆盖核心期刊/权威来源，是否有明显的文献遗漏领域
3. 引用标注：正文中的引用标注是否准确对应参考文献列表

请按以下 JSON 格式输出，不要输出任何其他文字：
{{
  "score": 82,
  "strengths": ["基于实际文献列表的具体优点1", "基于实际文献列表的具体优点2"],
  "weaknesses": ["具体条目+具体格式问题1", "具体条目+具体格式问题2"],
  "suggestions": ["针对具体问题的修正建议1", "针对具体问题的修正建议2"]
}}"""


# ─────────────────────────────────────────────────────────────
# 映射表
# ─────────────────────────────────────────────────────────────
PROMPT_TEMPLATES = {
    "academic_standard": PROMPT_ACADEMIC_STANDARD,
    "logic_innovation":  PROMPT_LOGIC_INNOVATION,
    "language_quality":  PROMPT_LANGUAGE_QUALITY,
    "citation_standard": PROMPT_CITATION_STANDARD,
}

DIMENSION_NAMES = {
    "academic_standard": "学术规范性",
    "logic_innovation":  "逻辑与创新性",
    "language_quality":  "语言质量",
    "citation_standard": "文献引用规范性",
}

# 各维度需要的 paper_struct 字段
DIMENSION_FIELDS = {
    "academic_standard": ["title", "outline", "abstract", "conclusion", "references"],
    "logic_innovation":  ["title", "outline", "chapter_summaries", "conclusion"],
    "language_quality":  ["title", "language_sample"],
    "citation_standard": ["title", "references", "citation_samples"],
}


def get_prompt(dimension: str, paper_struct: dict) -> str:
    """
    获取指定维度的提示词。
    paper_struct 由 evaluation.py 中的 _extract_structure() 返回。
    各维度只取自己需要的字段，不浪费 token。
    """
    if dimension not in PROMPT_TEMPLATES:
        raise ValueError(f"未知的评价维度: {dimension}")
    template = PROMPT_TEMPLATES[dimension]
    fields = DIMENSION_FIELDS[dimension]
    kwargs = {f: paper_struct.get(f, "（未提取到）") for f in fields}
    return template.format(**kwargs)


def get_dimension_name(dimension: str) -> str:
    return DIMENSION_NAMES.get(dimension, dimension)


def get_all_dimensions() -> list:
    return list(PROMPT_TEMPLATES.keys())
